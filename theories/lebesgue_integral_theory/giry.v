Definition giry_bind mu f : giry T2 R := (giry_join \o giry_map f) mu.

Local Notation "m >>= f" := (giry_bind m f).

Lemma measurable_giry_bind f :
  measurable_fun [set: giry T1 R] (fun mu => mu >>= f).
Proof. exact: (@measurableT_comp _ _ _ _ _ _ _ _ (giry_map f)). Qed.

Lemma giry_int_bind mu f (h : T2 -> \bar R) :
    measurable_fun [set: T2] h -> (forall x, 0 <= h x)%E ->
  giry_int (mu >>= f) h = giry_int mu (fun x => giry_int (f x) h).
Proof.
move=> mh h0; rewrite /giry_bind /= giry_int_join// giry_int_map//.
  exact: measurable_giry_int.
by move=> ?; exact: integral_ge0.
Qed.

End giry_bind.

Section giry_monad.
Context d1 d2 d3
  (T1 : measurableType d1)
  (T2 : measurableType d2)
  (T3 : measurableType d3)
  (f : {mfun T1 >-> T2})
  (g : {mfun T2 >-> T3})
  (R : realType).

(* G id = id *)
Lemma giry_map_id (x : giry T1 R):
  giry_map idfun x ≡μ @idfun (giry T1 R) x.
Proof.
  move => U H /=.
  rewrite /pushforward.
  rewrite /preimage /=.
  exact.
Qed.

(* G (g o f) = G g o G f *)
Lemma giry_map_comp (x : giry T1 R) :
  giry_map (g \o f) x ≡μ (giry_map g \o giry_map f) x.
  move => U H /=.
  rewrite /pushforward.
  by rewrite /preimage /=.
Qed.

(* Naturality of return *)
Lemma giry_ret_natural (x : T1) :
  (giry_map f \o (@giry_ret _ _ R)) x ≡μ (giry_ret \o f) x.
Proof.
  move => U H /=.
  by rewrite /dirac /= /pushforward /indic /preimage.
Qed.

(* Naturality of join *)
Lemma giry_join_natural (x : giry (giry T1 R) R) :
  (giry_join \o giry_map (giry_map f)) x ≡μ
  (giry_map f \o giry_join) x.
Proof.
move=> X mS/=; rewrite giry_joinE giry_int_map//.
rewrite /pushforward giry_joinE//.
exact: measurable_funPTI.
Qed.

(* Left unit *)
Lemma giry_join_Mret (x : giry T1 R) :
  (giry_join \o giry_map giry_ret) x ≡μ x.
Proof.
move=> A mA/=.
rewrite giry_joinE giry_int_map//.
by rewrite /giry_int /giry_ev /giry_ret/= /dirac integral_indic// setIT.
Qed.

(* Right unit *)
Lemma giry_join_retM (x : giry T1 R) :
  (giry_join \o giry_ret) x ≡μ x.
Proof. by move=> A mA/=; rewrite giry_joinE giry_int_ret. Qed.

Lemma giry_ev_join (A : mset T1) :
  giry_ev A \o giry_join = (@giry_int _ _ R)^~ (giry_ev A).
Proof.
apply/funext => ?/=; rewrite /giry_ev/= giry_joinE//.
exact: mset_is_measurable.
Qed.

(* Associativity *)
Lemma giry_joinA (x : giry (giry (giry T1 R) R) R) :
  (giry_join \o giry_map giry_join) x ≡μ
  (giry_join \o giry_join) x.
Proof.
move=> A mA/=.
by rewrite giry_joinE giry_int_map// giry_ev_join giry_joinE giry_int_join.
Qed.
End giry_monad.


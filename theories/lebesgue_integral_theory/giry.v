Lemma g_sigma_algebraSP {T : Type} (X Y : set_system T) :
  sigma_algebra [set: T] Y ->
  <<s X >> `<=` Y <-> X `<=` Y.
Proof.
move=> sY; split=> [sXY|]; last exact: smallest_sub.
by rewrite {sY}; apply: subset_trans sXY; exact: sub_gen_smallest.
Qed.

